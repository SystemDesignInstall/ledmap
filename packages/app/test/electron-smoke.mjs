  assert.match(await page.locator('#properties').innerText(), /Cabinet\s*Width\s*128 px\s*Height\s*128 px/)
  assert.equal(await page.locator('#properties').innerText().then(text => /128 px[\s\S]*128 px/.test(text)), true)

