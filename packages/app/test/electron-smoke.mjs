  assert.deepEqual(initial.map(s => [s.x, s.y]), [[0, 0], [700, 120], [320, 620]])
  assert.ok((await bounds()).width === 1084 && (await bounds()).height === 876)
  assert.match(await page.locator('#bounds').innerText(), /Project bounds 1,084 × 876 px/)
